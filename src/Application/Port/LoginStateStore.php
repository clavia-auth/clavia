declare(strict_types=1);

namespace Clavia\Application\Port;

use Clavia\Domain\Authentication\LoginState;

/**
 * Short-lived storage for pending sign-ins, keyed by an opaque handle.
 *
 * The handle is the only thing that ever reaches a URL or a form field. Entries expire
 * on their own after {@see LoginState::LIFETIME_SECONDS}. Reading does not consume: a
 * login page reads its handle on every render, and the entry is only forgotten once a
 * sign-in actually succeeds.
 */
interface LoginStateStore
{
    /**
     * @param non-empty-string $handle A fresh, high-entropy secret generated by the caller.
     */
    public function put(#[\SensitiveParameter] string $handle, LoginState $state): void;

    /**
     * Null for a missing, expired or unknown handle — indistinguishable on purpose:
     * there is nothing a caller could do differently for one than for another.
     */
    public function get(#[\SensitiveParameter] string $handle): ?LoginState;

    public function forget(#[\SensitiveParameter] string $handle): void;
}
