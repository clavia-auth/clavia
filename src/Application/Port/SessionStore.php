declare(strict_types=1);

namespace Clavia\Application\Port;

use Clavia\Domain\Authentication\Session;

/**
 * Where browser sessions live, keyed by the identifier the browser holds.
 *
 * Storage keeps only a digest of the identifier, so a dump of it cannot be replayed —
 * the same reasoning as for authorization codes and access tokens. An entry disappears
 * on its own when its time-to-live runs out; the time-to-live is the idle window, and
 * deciding it (and enforcing the absolute ceiling) is the caller's business.
 */
interface SessionStore
{
    /**
     * @param non-empty-string $sessionId  A fresh, high-entropy secret generated by the caller.
     * @param positive-int     $ttlSeconds
     */
    public function save(#[\SensitiveParameter] string $sessionId, Session $session, int $ttlSeconds): void;

    /**
     * Null for a missing, expired or unknown identifier — indistinguishable on purpose.
     */
    public function find(#[\SensitiveParameter] string $sessionId): ?Session;

    /**
     * Restart the time-to-live of a session that exists; nothing otherwise.
     *
     * @param positive-int $ttlSeconds
     */
    public function extend(#[\SensitiveParameter] string $sessionId, int $ttlSeconds): void;

    public function delete(#[\SensitiveParameter] string $sessionId): void;
}
