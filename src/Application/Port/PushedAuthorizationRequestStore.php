declare(strict_types=1);

namespace Clavia\Application\Port;

use Clavia\Domain\OAuth2\PushedAuthorizationRequest;

/**
 * Where pushed authorization requests wait for the browser (RFC 9126), behind the handle their
 * `request_uri` names, for a short while.
 *
 * Read as often as the browser comes back — a reload, or the return from the sign-in page
 * (§4: the server MAY allow a request to be repeated) — and spent once, when it yields a code.
 */
interface PushedAuthorizationRequestStore
{
    /**
     * @param non-empty-string $handle     A fresh, high-entropy secret generated by the caller.
     * @param positive-int     $ttlSeconds
     */
    public function push(
        #[\SensitiveParameter] string $handle,
        PushedAuthorizationRequest $request,
        int $ttlSeconds,
    ): void;

    /** Null for an unknown, expired or spent handle — indistinguishable on purpose. */
    public function find(#[\SensitiveParameter] string $handle): ?PushedAuthorizationRequest;

    /**
     * Remove the request, atomically: true for the one caller that did, so of two codes asked on
     * one request only one is issued.
     */
    #[\NoDiscard]
    public function spend(#[\SensitiveParameter] string $handle): bool;
}
