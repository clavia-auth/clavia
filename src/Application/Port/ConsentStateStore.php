declare(strict_types=1);

namespace Clavia\Application\Port;

use Clavia\Domain\Consent\PendingConsent;

/**
 * Authorization requests on hold behind the consent screen, keyed by the opaque handle
 * the browser carries there, for {@see PendingConsent::LIFETIME_SECONDS}. Stored as the
 * handle's digest, like every handle a browser holds.
 */
interface ConsentStateStore
{
    /**
     * @param non-empty-string $handle A fresh, high-entropy secret generated by the caller.
     */
    public function park(#[\SensitiveParameter] string $handle, PendingConsent $pending): void;

    /**
     * The request on hold, left in place: showing the screen decides nothing. Null for a
     * missing, expired or unknown handle — indistinguishable on purpose.
     */
    public function find(#[\SensitiveParameter] string $handle): ?PendingConsent;

    /**
     * Read **and remove** the request, atomically: a decision is made once, even by two
     * submissions racing with it.
     */
    public function claim(#[\SensitiveParameter] string $handle): ?PendingConsent;
}
